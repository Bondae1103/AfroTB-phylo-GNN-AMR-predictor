"""Entry point for the protocol x split x architecture x seed benchmark.

Usage
-----
    # against the real data, once data/processed/ exists
    .venv/Scripts/python.exe -m src.experiments.run_benchmark

    # against the synthetic replica (no real data required)
    .venv/Scripts/python.exe -m src.experiments.run_benchmark --dir data/synthetic/full

Output goes to results/protocol_benchmark.json for real data, or to
<dir>/protocol_benchmark.json for any other directory -- synthetic numbers are
kept OUT of results/ so they can never be confused with Afro-TB findings.
"""

import argparse
import json
from pathlib import Path

from ..protocols import features as featmod
from . import benchmark

REAL_PROCESSED = Path("data/processed")
REAL_RESULTS = Path("results/protocol_benchmark.json")


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--dir", default=str(REAL_PROCESSED),
                    help="processed-data directory (default: data/processed)")
    ap.add_argument("--seeds", type=int, nargs="+", default=[0, 1, 2])
    ap.add_argument("--architectures", nargs="+",
                    default=["mlp_only", "gcn_skip", "gatv2", "gated_hybrid",
                             "random_forest"])
    ap.add_argument("--protocols", nargs="+",
                    default=[featmod.CATALOGUE, featmod.GENOMEWIDE])
    ap.add_argument("--splits", nargs="+", default=["original", "phylo_clade"])
    ap.add_argument("--max-genomewide-sites", type=int, default=1500)
    ap.add_argument("--clade-threshold", type=float, default=0.40)
    ap.add_argument("--max-epochs", type=int, default=300)
    ap.add_argument("--patience", type=int, default=60)
    ap.add_argument("--lr", type=float, default=0.05)
    ap.add_argument("--lambda-lineage", type=float, default=0.0)
    ap.add_argument("--out", default=None)
    args = ap.parse_args()

    processed = Path(args.dir)
    is_real = processed.resolve() == REAL_PROCESSED.resolve()
    out = Path(args.out) if args.out else (
        REAL_RESULTS if is_real else processed / "protocol_benchmark.json")

    print("processed dir : %s" % processed)
    print("output        : %s" % out)
    if not is_real:
        print("NOTE: this is NOT data/processed -- results are not Afro-TB findings.")
    print()

    results = benchmark.run(
        processed,
        architectures=tuple(args.architectures),
        protocols=tuple(args.protocols),
        split_names=tuple(args.splits),
        seeds=tuple(args.seeds),
        max_genomewide_sites=args.max_genomewide_sites,
        clade_threshold=args.clade_threshold,
        max_epochs=args.max_epochs,
        patience=args.patience,
        lr=args.lr,
        lambda_lineage=args.lambda_lineage,
    )
    if not is_real:
        results["WARNING"] = (
            "SYNTHETIC DATA -- generated by src/synthetic/afrotb_replica.py. "
            "Not Afro-TB. Never cite as a biological or dataset result."
        )
    results["summary_table"] = benchmark.summarise(results)

    out.parent.mkdir(parents=True, exist_ok=True)
    with open(out, "w", encoding="utf-8") as f:
        json.dump(results, f, indent=2)

    print("\n%-12s %-12s %-15s %8s  %-18s %s" % (
        "SPLIT", "PROTOCOL", "ARCHITECTURE", "#FEAT", "TEST core-6 F1", "TEST all-9 F1"))
    print("-" * 92)
    for r in results["summary_table"]:
        print("%-12s %-12s %-15s %8d  %.4f +/- %.4f   %.4f" % (
            r["split"], r["protocol"], r["architecture"], r["n_features"],
            r["test_core6_f1_mean"], r["test_core6_f1_std"], r["test_all9_f1_mean"]))
    print("\nWrote %s" % out)


if __name__ == "__main__":
    main()
